<?php
/**
 * Theme builder: draft block themes with a private preview link.
 *
 * A draft theme is a block theme made only of data - style.css (header only), theme.json (design tokens,
 * global styles and the CSS, in styles.css), templates/*.html and parts/*.html block markup. No PHP file is
 * ever written, so a draft cannot run code. Drafts live in wp-content/themes/wpu-<name>/ and are marked so
 * these tools never touch any other theme.
 *
 * Preview: a link with a random key (stored hashed, expires) shows the site with the draft theme to whoever
 * opens it, without activating it. Previews are noindex and never cached. Admins also get the Site Editor
 * preview link.
 */

if ( ! defined( 'ABSPATH' ) ) {
	exit;
}

const WPU_BT_THEME_MARK = 'Generated by WPU Bridge (draft theme).';

function wpu_bt_themes_on() {
	return (bool) wpu_bt_setting( 'allow_themes' );
}

function wpu_bt_theme_slug( $name ) {
	$s = sanitize_title( remove_accents( (string) $name ) );
	$s = trim( preg_replace( '/-+/', '-', preg_replace( '/[^a-z0-9-]/', '-', strtolower( $s ) ) ), '-' );
	$s = trim( substr( preg_replace( '/^wpu-/', '', $s ), 0, 40 ), '-' );
	return '' === $s ? '' : 'wpu-' . $s;
}

function wpu_bt_theme_dir( $slug ) {
	return get_theme_root() . '/' . $slug;
}

/** True when $slug is a draft theme these tools made. */
function wpu_bt_is_draft_theme( $slug ) {
	if ( ! is_string( $slug ) || ! preg_match( '/^wpu-[a-z0-9-]{1,40}$/', $slug ) ) {
		return false;
	}
	$css = wpu_bt_theme_dir( $slug ) . '/style.css';
	return is_file( $css ) && ! is_link( wpu_bt_theme_dir( $slug ) ) && false !== strpos( (string) file_get_contents( $css, false, null, 0, 2000 ), WPU_BT_THEME_MARK ); // phpcs:ignore WordPress.WP.AlternativeFunctions
}

/** CSS for theme.json styles.css: plain CSS only. */
function wpu_bt_clean_css( $css ) {
	$css = (string) $css;
	if ( strlen( $css ) > 300000 ) {
		return wpu_bt_err( 'CSS is larger than 300 KB.' );
	}
	if ( preg_match( '/<|expression\s*\(|javascript:|behavior\s*:|-moz-binding|@import/i', $css ) ) {
		return wpu_bt_err( 'CSS may not contain "<", @import, javascript:, expression() or behaviors. Inline the rules instead of importing.' );
	}
	return $css;
}

/** Template and part names: WordPress template hierarchy style names only. */
function wpu_bt_tpl_name_ok( $name ) {
	return is_string( $name ) && preg_match( '/^[a-z0-9][a-z0-9-]{0,60}$/', $name );
}

/** Block markup for a template or part, filtered like post content and checked. */
function wpu_bt_tpl_markup( $markup, &$warnings, $label ) {
	if ( strlen( (string) $markup ) > 500000 ) {
		return wpu_bt_err( $label . ' is larger than 500 KB.' );
	}
	list( $clean, $w ) = wpu_bt_clean_content( (string) $markup );
	foreach ( $w as $x ) {
		$warnings[] = $label . ': ' . $x;
	}
	return $clean;
}

/** Current files of a draft (relative path => contents). */
function wpu_bt_theme_files( $slug ) {
	$dir   = wpu_bt_theme_dir( $slug );
	$files = array();
	foreach ( array( 'style.css', 'theme.json' ) as $f ) {
		if ( is_file( "$dir/$f" ) ) {
			$files[ $f ] = (string) file_get_contents( "$dir/$f" ); // phpcs:ignore WordPress.WP.AlternativeFunctions
		}
	}
	foreach ( array( 'templates', 'parts' ) as $sub ) {
		foreach ( (array) glob( "$dir/$sub/*.html" ) as $path ) {
			if ( is_file( $path ) && ! is_link( $path ) ) {
				$files[ "$sub/" . basename( $path ) ] = (string) file_get_contents( $path ); // phpcs:ignore WordPress.WP.AlternativeFunctions
			}
		}
	}
	return $files;
}

/** Write files into a draft theme folder. Paths were built by this file from checked names only. */
function wpu_bt_theme_write( $slug, array $files ) {
	$dir = wpu_bt_theme_dir( $slug );
	foreach ( $files as $rel => $body ) {
		if ( ! preg_match( '#^(style\.css|theme\.json|(templates|parts)/[a-z0-9][a-z0-9-]{0,60}\.html)$#', $rel ) ) {
			return false;
		}
		$path = "$dir/$rel";
		if ( ! wp_mkdir_p( dirname( $path ) ) || is_link( $path ) ) {
			return false;
		}
		if ( null === $body ) {
			wp_delete_file( $path );
		} elseif ( false === file_put_contents( $path, $body ) ) { // phpcs:ignore WordPress.WP.AlternativeFunctions
			return false;
		}
	}
	wp_clean_themes_cache();
	return true;
}

/* -------------------------------------------------------------------------
 * Preview links
 * ---------------------------------------------------------------------- */

function wpu_bt_preview_new( $slug, $days ) {
	$token = strtolower( wp_generate_password( 32, false ) );
	$all   = (array) get_option( 'wpu_bt_theme_previews', array() );
	foreach ( $all as $k => $p ) {
		if ( (int) $p['exp'] < time() ) {
			unset( $all[ $k ] );
		}
	}
	$exp                                  = time() + max( 1, min( 30, (int) $days ) ) * DAY_IN_SECONDS;
	$all[ substr( hash( 'sha256', $token ), 0, 32 ) ] = array( 'slug' => $slug, 'exp' => $exp );
	update_option( 'wpu_bt_theme_previews', array_slice( $all, -50, null, true ), false );
	return array( 'url' => add_query_arg( 'wpu_preview', $slug . '.' . $token, home_url( '/' ) ), 'expires' => gmdate( 'c', $exp ) );
}

/** The draft slug a valid preview value points at, or ''. */
function wpu_bt_preview_check( $value ) {
	if ( ! is_string( $value ) || ! preg_match( '/^(wpu-[a-z0-9-]{1,40})\.([a-z0-9]{32})$/', $value, $m ) ) {
		return '';
	}
	$all = (array) get_option( 'wpu_bt_theme_previews', array() );
	$key = substr( hash( 'sha256', $m[2] ), 0, 32 );
	if ( ! isset( $all[ $key ] ) || $all[ $key ]['slug'] !== $m[1] || (int) $all[ $key ]['exp'] < time() ) {
		return '';
	}
	return wpu_bt_is_draft_theme( $m[1] ) ? $m[1] : '';
}

/**
 * Switch the theme for this request only, before WordPress loads the theme (this file runs while plugins load).
 * Front end only; never in wp-admin, cron, the REST API's admin routes or the bridge itself.
 */
( function () {
	if ( wpu_bt_is_disabled() || ! wpu_bt_themes_on() || is_admin() || wp_doing_cron() || ( defined( 'WP_CLI' ) && WP_CLI ) ) {
		return;
	}
	$uri = isset( $_SERVER['REQUEST_URI'] ) ? rawurldecode( (string) wp_unslash( $_SERVER['REQUEST_URI'] ) ) : ''; // phpcs:ignore WordPress.Security.ValidatedSanitizedInput.InputNotSanitized -- only matched below
	if ( isset( $_GET['rest_route'] ) || false !== strpos( $uri, '/' . rest_get_url_prefix() . '/' ) || false !== stripos( $uri, 'rest_route' ) ) { // phpcs:ignore WordPress.Security.NonceVerification.Recommended
		return;
	}
	$param  = isset( $_GET['wpu_preview'] ) ? sanitize_text_field( wp_unslash( $_GET['wpu_preview'] ) ) : null; // phpcs:ignore WordPress.Security.NonceVerification.Recommended -- the value is a random preview key, checked against stored hashes
	$cookie = isset( $_COOKIE['wpu_theme_preview'] ) ? sanitize_text_field( wp_unslash( $_COOKIE['wpu_theme_preview'] ) ) : '';
	if ( 'off' === $param ) {
		setcookie( 'wpu_theme_preview', '', time() - 3600, COOKIEPATH ? COOKIEPATH : '/', COOKIE_DOMAIN, is_ssl(), true );
		return;
	}
	$value = null !== $param ? $param : $cookie;
	if ( '' === $value ) {
		return;
	}
	// The theme folder and the stored keys are read before the theme loads: options are available here.
	$slug = wpu_bt_preview_check( $value );
	if ( '' === $slug ) {
		return;
	}
	if ( null !== $param && ! headers_sent() ) {
		setcookie( 'wpu_theme_preview', $value, array(
			'expires'  => time() + DAY_IN_SECONDS,
			'path'     => COOKIEPATH ? COOKIEPATH : '/',
			'domain'   => COOKIE_DOMAIN,
			'secure'   => is_ssl(),
			'httponly' => true,
			'samesite' => 'Lax',
		) );
	}
	$GLOBALS['wpu_bt_previewing'] = $slug;
	$use = function () use ( $slug ) {
		return $slug;
	};
	add_filter( 'stylesheet', $use, 999 );
	add_filter( 'template', $use, 999 );
	// If this still turns out to be a REST request, drop the preview at once.
	add_action( 'parse_request', function () use ( $use ) {
		if ( ( defined( 'REST_REQUEST' ) && REST_REQUEST ) || ( function_exists( 'wp_is_serving_rest_request' ) && wp_is_serving_rest_request() ) ) {
			remove_filter( 'stylesheet', $use, 999 );
			remove_filter( 'template', $use, 999 );
		}
	}, 0 );
	if ( ! defined( 'DONOTCACHEPAGE' ) ) {
		define( 'DONOTCACHEPAGE', true );
	}
	add_action( 'send_headers', function () {
		header( 'X-Robots-Tag: noindex, nofollow' );
		nocache_headers();
	} );
	$bar = function () use ( $slug ) {
		static $done = false;
		if ( $done ) {
			return;
		}
		$done  = true;
		$theme = wp_get_theme( $slug );
		echo '<div style="position:fixed;z-index:999999;left:12px;bottom:12px;background:#1d2327;color:#fff;font:13px/1.4 -apple-system,Segoe UI,sans-serif;padding:8px 12px;border-radius:6px;box-shadow:0 2px 8px rgba(0,0,0,.3)">'
			. 'Preview of draft theme <strong>' . esc_html( $theme->get( 'Name' ) ) . '</strong> - not live. '
			. '<a style="color:#72aee6" href="' . esc_url( add_query_arg( 'wpu_preview', 'off', home_url( '/' ) ) ) . '">Exit preview</a></div>';
	};
	add_action( 'wp_body_open', $bar );
	add_action( 'wp_footer', $bar );
} )();

