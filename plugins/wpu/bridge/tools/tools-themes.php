wpu_bt_define_tool( 'theme_activate', array(
	'title'       => 'Activate a theme',
	'description' => 'Make an installed theme (a WPU draft or any other) the live theme. Changes how the whole site looks for every visitor: only when the person asks. Returns a change_id; undo switches back to the previous theme.',
	'cap'         => 'switch_themes',
	'group'       => 'themes',
	'props'       => array( 'theme' => array( 'type' => 'string', 'description' => 'Theme folder name (stylesheet).' ) ),
	'required'    => array( 'theme' ),
	'write'       => true,
	'destructive' => true,
	'run'         => function ( $a ) {
		$slug = (string) $a['theme'];
		if ( ! wpu_bt_installed_theme( $slug ) ) {
			return wpu_bt_err( 'Not an installed theme: ' . sanitize_text_field( $slug ) . '. Use the folder name from Appearance > Themes.' );
		}
		$t = wp_get_theme( $slug );
		if ( ! $t->exists() || $t->errors() ) {
			return wpu_bt_err( 'Theme not installed or broken: ' . $slug );
		}
		$prev = get_stylesheet();
		if ( $prev === $slug ) {
			return array( 'theme' => $slug, 'note' => 'Already active.' );
		}
		switch_theme( $slug );
		$health = wpu_bt_health( array( home_url( '/' ) ) );
		$cid    = wpu_bt_change_add( 'theme_activate', 'Activated theme ' . $slug . ' (was ' . $prev . ')', array( 'kind' => 'theme_switch', 'theme' => $prev ) );
		return array( 'theme' => $slug, 'previous' => $prev, 'home_page' => $health[0], 'change_id' => $cid );
	},
) );

/** True only for a plain folder name of a theme WordPress lists as installed. */
function wpu_bt_installed_theme( $slug ) {
	return is_string( $slug ) && preg_match( '/^[A-Za-z0-9._-]+$/', $slug ) && false === strpos( $slug, '..' ) && 0 === validate_file( $slug ) && array_key_exists( $slug, wp_get_themes() ) && wp_get_theme( $slug )->is_allowed(); // is_allowed: on multisite, only themes enabled for this site
}

/** Can theme files be written here, by this person? '' when yes. */
function wpu_bt_theme_write_blocker() {
	if ( ! current_user_can( 'install_themes' ) ) {
		return 'You cannot add themes on this site.';
	}
	if ( defined( 'DISALLOW_FILE_MODS' ) && DISALLOW_FILE_MODS ) {
		return 'This site sets DISALLOW_FILE_MODS, so themes cannot be added from WordPress.';
	}
	require_once ABSPATH . 'wp-admin/includes/file.php';
	if ( 'direct' !== get_filesystem_method( array(), get_theme_root() ) ) {
		return 'WordPress cannot write to the themes folder on this host without FTP details.';
	}
	return '';
}

/** Undo for theme changes. */
function wpu_bt_theme_undo( array $p ) {
	if ( ! wpu_bt_themes_on() ) {
		return wpu_bt_err( 'Theme changes are switched off on this site (Tools > WPU Bridge).' );
	}
	if ( 'theme_switch' === $p['kind'] ) {
		if ( ! current_user_can( 'switch_themes' ) || ! wpu_bt_installed_theme( (string) $p['theme'] ) ) {
			return wpu_bt_err( 'The previous theme is no longer installed, or you cannot switch themes.' );
		}
		switch_theme( (string) $p['theme'] );
		return array( 'theme' => $p['theme'] );
	}
	$block = wpu_bt_theme_write_blocker();
	if ( '' !== $block ) {
		return wpu_bt_err( $block );
	}
	$slug = (string) $p['slug'];
	if ( ! wpu_bt_is_draft_theme( $slug ) ) {
		return wpu_bt_err( 'That draft theme is gone or was changed outside WPU Bridge.' );
	}
	if ( ! empty( $p['delete_theme'] ) ) {
		if ( get_stylesheet() === $slug || get_template() === $slug ) {
			return wpu_bt_err( 'This draft is the live theme now. Activate another theme first.' );
		}
		$dir  = wp_normalize_path( (string) realpath( wpu_bt_theme_dir( $slug ) ) );
		$root = wp_normalize_path( (string) realpath( get_theme_root() ) );
		if ( '' === $dir || dirname( $dir ) !== $root ) {
			return wpu_bt_err( 'The draft theme folder is not where it should be.' );
		}
		wpu_bt_rrmdir_any( $dir );
		wp_clean_themes_cache();
		return array( 'removed' => $slug );
	}
	if ( ! wpu_bt_theme_write( $slug, (array) $p['files'] ) ) {
		return wpu_bt_err( 'Could not put the previous files back.' );
	}
	return array( 'theme' => $slug, 'restored' => array_keys( (array) $p['files'] ) );
}
