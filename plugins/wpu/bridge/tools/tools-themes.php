wpu_bt_define_tool( 'theme_draft_save', array(
	'title'       => 'Create or update a draft theme',
	'description' => 'Build a block theme as a draft, not active, with no PHP: theme_json (colours, fonts, spacing, layout widths, element and block styles), css (plain CSS, e.g. compiled Tailwind utilities, max 300 KB; stored in theme.json styles.css), templates (name => block markup; "index" is required for a new theme; e.g. front-page, home, page, single, archive, search, 404) and parts (name => block markup, e.g. header, footer). '
		. 'Template parts are used with <!-- wp:template-part {"slug":"header","tagName":"header"} /-->. Updating a draft replaces only the files you send. Returns a private preview link (anyone with it can see the site in this theme without it going live) and the Site Editor preview. Returns a change_id; undo removes a new draft or puts the previous files back.',
	'cap'         => 'edit_theme_options',
	'group'       => 'themes',
	'props'       => array(
		'name'        => array( 'type' => 'string', 'description' => 'Theme name, e.g. "Acme Dental 2026". The folder is wpu-<name>.' ),
		'description' => array( 'type' => 'string' ),
		'theme_json'  => array( 'type' => 'object', 'description' => 'theme.json contents (version 3).' ),
		'css'         => array( 'type' => 'string' ),
		'templates'   => array( 'type' => 'object', 'description' => 'name => block markup' ),
		'parts'       => array( 'type' => 'object', 'description' => 'name => block markup' ),
		'preview_days' => array( 'type' => 'integer', 'description' => 'How long the preview link works, 1-30 days (default 7).' ),
		'confirm_live' => array( 'type' => 'boolean', 'description' => 'Only when the person agreed to change a draft that is already the live theme.' ),
	),
	'required'    => array( 'name' ),
	'write'       => true,
	'run'         => function ( $a ) {
		$block = wpu_bt_theme_write_blocker();
		if ( '' !== $block ) {
			return wpu_bt_err( $block );
		}
		$slug = wpu_bt_theme_slug( $a['name'] );
		if ( '' === $slug ) {
			return wpu_bt_err( 'Give the theme a name with letters or numbers.' );
		}
		$dir   = wpu_bt_theme_dir( $slug );
		$isnew = ! file_exists( $dir );
		if ( ! $isnew && ! wpu_bt_is_draft_theme( $slug ) ) {
			return wpu_bt_err( 'A theme folder called ' . $slug . ' already exists and was not made by WPU Bridge. Pick another name.' );
		}
		if ( ! $isnew && ( get_stylesheet() === $slug || get_template() === $slug ) && ! wpu_bt_bool( $a, 'confirm_live' ) ) {
			return wpu_bt_err( 'This draft is now the LIVE theme, so saving changes the site for every visitor. Send confirm_live true only if the person agreed.' );
		}
		$warnings = array();
		$files    = array();

		// theme.json (with the CSS inside)
		$old_json = $isnew ? array() : json_decode( (string) @file_get_contents( "$dir/theme.json" ), true ); // phpcs:ignore WordPress.WP.AlternativeFunctions,WordPress.PHP.NoSilencedErrors
		$json     = isset( $a['theme_json'] ) ? (array) $a['theme_json'] : ( is_array( $old_json ) && $old_json ? $old_json : array() );
		if ( isset( $a['css'] ) ) {
			$css = wpu_bt_clean_css( $a['css'] );
			if ( is_wp_error( $css ) ) {
				return $css;
			}
			$json['styles']        = isset( $json['styles'] ) && is_array( $json['styles'] ) ? $json['styles'] : array();
			$json['styles']['css'] = $css;
		} elseif ( isset( $json['styles']['css'] ) ) {
			$css = wpu_bt_clean_css( $json['styles']['css'] );
			if ( is_wp_error( $css ) ) {
				return $css;
			}
		}
		if ( isset( $a['theme_json'] ) || isset( $a['css'] ) || $isnew ) {
			unset( $json['$schema'] );
			$json = array( '$schema' => 'https://schemas.wp.org/trunk/theme.json' ) + $json;
			$json['version'] = isset( $json['version'] ) && in_array( (int) $json['version'], array( 2, 3 ), true ) ? (int) $json['version'] : 3;
			if ( isset( $json['customTemplates'] ) && ! is_array( $json['customTemplates'] ) ) {
				return wpu_bt_err( 'theme_json customTemplates must be a list.' );
			}
			$encoded = wp_json_encode( $json, JSON_PRETTY_PRINT | JSON_UNESCAPED_SLASHES | JSON_UNESCAPED_UNICODE );
			if ( ! $encoded || strlen( $encoded ) > 800000 ) {
				return wpu_bt_err( 'theme_json is empty or too large.' );
			}
			$files['theme.json'] = $encoded . "\n";
		}

		foreach ( array( 'templates', 'parts' ) as $sub ) {
			foreach ( isset( $a[ $sub ] ) ? (array) $a[ $sub ] : array() as $name => $markup ) {
				if ( ! wpu_bt_tpl_name_ok( $name ) ) {
					return wpu_bt_err( $sub . ' name "' . $name . '" is not allowed: lowercase letters, numbers and dashes only.' );
				}
				$clean = wpu_bt_tpl_markup( $markup, $warnings, $sub . '/' . $name );
				if ( is_wp_error( $clean ) ) {
					return $clean;
				}
				$files[ "$sub/$name.html" ] = $clean;
			}
		}
		if ( $isnew && ! isset( $files['templates/index.html'] ) ) {
			return wpu_bt_err( 'A new theme needs templates.index (the fallback template).' );
		}
		if ( $isnew || isset( $a['description'] ) ) {
			$name = sanitize_text_field( (string) $a['name'] );
			$desc = isset( $a['description'] ) ? sanitize_text_field( (string) $a['description'] ) : 'Draft block theme.';
			$files['style.css'] = "/*\nTheme Name: " . str_replace( '*/', '', $name ) . "\nDescription: " . str_replace( '*/', '', $desc ) . "\nVersion: 0.1.0\nRequires at least: 6.6\nRequires PHP: 7.4\nText Domain: $slug\nTags: full-site-editing, block-patterns\n\n" . WPU_BT_THEME_MARK . "\nNo PHP files: theme.json, templates and parts only.\n*/\n";
		}
		if ( count( $files ) > 60 ) {
			return wpu_bt_err( 'At most 60 files per call.' );
		}

		$before = $isnew ? array() : wpu_bt_theme_files( $slug );
		if ( ! wpu_bt_theme_write( $slug, $files ) ) {
			return wpu_bt_err( 'Could not write the theme files.' );
		}
		if ( ! wpu_bt_is_draft_theme( $slug ) ) {
			return wpu_bt_err( 'The theme folder could not be created.' );
		}
		if ( $isnew ) {
			$undo = array( 'kind' => 'theme_files', 'slug' => $slug, 'delete_theme' => true );
		} else {
			$restore = array();
			foreach ( array_keys( $files ) as $rel ) {
				$restore[ $rel ] = array_key_exists( $rel, $before ) ? $before[ $rel ] : null;
			}
			$undo = array( 'kind' => 'theme_files', 'slug' => $slug, 'files' => $restore );
		}
		$cid  = wpu_bt_change_add( 'theme_draft_save', ( $isnew ? 'Created' : 'Updated' ) . ' draft theme ' . $slug . ' (' . count( $files ) . ' files)', $undo );
		$prev = wpu_bt_preview_new( $slug, wpu_bt_int( $a, 'preview_days', 7, 1, 30 ) );
		$theme = wp_get_theme( $slug );
		return array(
			'theme'            => $slug,
			'created'          => $isnew,
			'files'            => array_keys( $files ),
			'valid'            => $theme->exists() && ! $theme->errors(),
			'warnings'         => $warnings,
			'preview_url'      => $prev['url'],
			'preview_expires'  => $prev['expires'],
			'site_editor_url'  => admin_url( 'site-editor.php?wp_theme_preview=' . rawurlencode( $slug ) ),
			'change_id'        => $cid,
		);
	},
) );

wpu_bt_define_tool( 'theme_drafts_list', array(
	'title'       => 'List draft themes',
	'description' => 'Draft themes made by WPU Bridge, plus which theme is active.',
	'cap'         => 'edit_theme_options',
	'group'       => 'themes',
	'run'         => function () {
		$out = array();
		foreach ( wp_get_themes() as $slug => $t ) {
			if ( wpu_bt_is_draft_theme( $slug ) ) {
				$out[] = array( 'theme' => $slug, 'name' => $t->get( 'Name' ), 'active' => get_stylesheet() === $slug, 'files' => array_keys( wpu_bt_theme_files( $slug ) ) );
			}
		}
		return array( 'active_theme' => get_stylesheet(), 'drafts' => $out );
	},
) );

